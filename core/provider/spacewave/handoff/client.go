// StartHandoff initiates browser-delegated auth by opening a browser
// and waiting for authorization of a Session key generated by this client.
//
// Returns this client's private key and the provider account to verify and mount.
func StartHandoff(
	ctx context.Context,
	httpCli *http.Client,
	apiEndpoint string,
	publicBaseURL string,
	clientType string,
	authIntent string,
	username string,
) (crypto.PrivKey, string, string, error) {
	// Track the auth session cleanup, defaulting to a no-op until the session exists.
	var nonce string
	var wsTicket string
	cleanupSession := func() {}
	defer func() {
		cleanupSession()
	}()

	// Generate the receiving Session's key locally; only its public key leaves.
	ephPriv, ephPub, err := crypto.GenerateEd25519Key(rand.Reader)
	if err != nil {
		return nil, "", "", errors.Wrap(err, "generate ephemeral keypair")
	}

	// Derive the raw ephemeral public key bytes for the HandoffRequest.
	ephPubRaw, err := ephPub.Raw()
	if err != nil {
		return nil, "", "", errors.Wrap(err, "get ephemeral public key bytes")
	}

	// Build the session_handoff.HandoffRequest proto describing this device.
	nonce = ulid.NewULID()
	deviceName := getDeviceName()
	if clientType == "" {
		clientType = "desktop"
	}
	handoffReq := &session_handoff.HandoffRequest{
		DevicePublicKey: ephPubRaw,
		DeviceName:      deviceName,
		SessionNonce:    nonce,
		ClientType:      clientType,
		ProtocolVersion: 1,
	}

	// Marshal the api.AuthSessionCreateRequest and build its POST request.
	createReq := &api.AuthSessionCreateRequest{Nonce: nonce}
	createBody, err := createReq.MarshalVT()
	if err != nil {
		return nil, "", "", errors.Wrap(err, "marshal create request")
	}
	createURL := buildCreateSessionURL(apiEndpoint)
	httpReq, err := http.NewRequestWithContext(ctx, http.MethodPost, createURL, bytes.NewReader(createBody))
	if err != nil {
		return nil, "", "", errors.Wrap(err, "build create request")
	}
	httpReq.Header.Set("Content-Type", "application/octet-stream")

	// Send the create-session POST and read the response body.
	httpResp, err := httpCli.Do(httpReq)
	if err != nil {
		return nil, "", "", errors.Wrap(err, "create auth session")
	}
	defer httpclient.DrainAndCloseResponseBody(httpResp)
	respBody, err := io.ReadAll(httpResp.Body)
	if err != nil {
		return nil, "", "", errors.Wrap(err, "read create auth session response")
	}
	if httpResp.StatusCode != http.StatusOK {
		return nil, "", "", errors.Errorf("create auth session failed: %d: %s", httpResp.StatusCode, string(respBody))
	}

	// Parse the api.AuthSessionCreateResponse and arm the auth-session cleanup.
	var createResp api.AuthSessionCreateResponse
	if err := createResp.UnmarshalVT(respBody); err != nil {
		return nil, "", "", errors.Wrap(err, "parse create response")
	}
	wsTicket = createResp.GetWsTicket()
	if wsTicket == "" {
		return nil, "", "", errors.New("server did not return an auth session websocket ticket")
	}
	cleanupSession = func() {
		cleanupAuthSession(httpCli, apiEndpoint, nonce, wsTicket)
	}

	// Open the browser at the handoff URL carrying the encoded HandoffRequest.
	reqData, err := handoffReq.MarshalVT()
	if err != nil {
		return nil, "", "", errors.Wrap(err, "marshal handoff request")
	}
	payload := base64.RawURLEncoding.EncodeToString(reqData)
	authURL := buildHandoffBrowserURL(publicBaseURL, payload, authIntent, username)
	if openErr := openBrowserValidated(authURL, hostsFromURLs(publicBaseURL)); openErr != nil {
		return nil, "", "", errors.Wrap(openErr, "open browser")
	}

	// Wait on the auth-session WebSocket for the provider's registration result.
	conn, msg, err := readHandoffResult(ctx, buildHandoffWSURL(apiEndpoint, wsTicket))
	if err != nil {
		return nil, "", "", err
	}
	defer conn.Close(websocket.StatusNormalClosure, "")

	// Parse the api.WsAuthSessionServerFrame and extract the HandoffCompletion.
	var frame api.WsAuthSessionServerFrame
	if err := frame.UnmarshalVT(msg); err != nil {
		return nil, "", "", errors.Wrap(err, "unmarshal auth-session frame")
	}
	completionFrame, ok := frame.GetBody().(*api.WsAuthSessionServerFrame_Completion)
	if !ok || completionFrame.Completion == nil {
		return nil, "", "", errors.New("auth-session frame missing completion")
	}
	completion := completionFrame.Completion

	// Verify the completion authorizes this client's receiving Session key.
	receivingPeer, err := peer.IDFromPublicKey(ephPub)
	if err != nil {
		return nil, "", "", err
	}
	if completion.GetSessionPeerId() != receivingPeer.String() || completion.GetAccountId() == "" {
		return nil, "", "", errors.New("browser did not authorize this client's Session key; update both clients and link again")
	}

	// Send the session_handoff.HandoffAck over the WebSocket.
	ack := &session_handoff.HandoffAck{}
	ackData, err := ack.MarshalVT()
	if err != nil {
		return nil, "", "", errors.Wrap(err, "marshal handoff ack")
	}
	if err := conn.Write(ctx, websocket.MessageBinary, ackData); err != nil {
		return nil, "", "", errors.Wrap(err, "send handoff ack")
	}

	// Stop the session cleanup and return the provider account to mount.
	cleanupSession = func() {}
	return ephPriv, completion.GetAccountId(), completion.GetEntityId(), nil
}

// maxHandoffRedials bounds consecutive failed attempts to reach the auth
// session after its WebSocket drops.
const maxHandoffRedials = 5

// readHandoffResult connects the auth-session WebSocket and reads the
// provider's result frame, returning the open connection with the frame.
// The server drops the socket without a close frame when it restarts, so a
// dropped socket is redialed with backoff. A close frame ends the wait.
func readHandoffResult(ctx context.Context, wsURL string) (*websocket.Conn, []byte, error) {
	delay := time.Second
	var failures int
	for {
		// Dial and read one frame; a successful dial resets the failure count.
		conn, _, err := websocket.Dial(ctx, wsURL, nil)
		if err == nil {
			failures = 0
			var msg []byte
			_, msg, err = conn.Read(ctx)
			if err == nil {
				return conn, msg, nil
			}
			_ = conn.Close(websocket.StatusNormalClosure, "")
		}

		// Stop on a close frame, cancellation, or too many failures.
		failures++
		if ctx.Err() != nil || failures > maxHandoffRedials || !isDroppedSocket(err) {
			return nil, nil, describeHandoffWaitErr(err)
		}

		// Wait out the backoff before redialing.
		select {
		case <-ctx.Done():
			return nil, nil, ctx.Err()
		case <-time.After(delay):
		}
		delay = min(delay*2, 16*time.Second)
	}
}

// isDroppedSocket reports whether err is a connection lost without a close
// frame, as opposed to the server ending the auth session.
func isDroppedSocket(err error) bool {
	status := websocket.CloseStatus(err)
	return status == -1 || status == websocket.StatusAbnormalClosure
}

// describeHandoffWaitErr explains why waiting for the browser ended.
func describeHandoffWaitErr(err error) error {
	switch websocket.CloseStatus(err) {
	case 4008:
		return errors.New("the sign-in link expired; run the command again")
	case 4000:
		return errors.New("the sign-in was canceled; run the command again")
	}
	return errors.Wrap(err, "wait for browser sign-in")
}

// getDeviceName returns the hostname or a fallback device name.
func getDeviceName() string {
	name, err := os.Hostname()
	if err != nil || name == "" {
		return "Desktop"
	}
	return name
}

// openBrowserValidated opens the default browser to the given URL after
// validating that the URL uses https, or http for loopback hosts only, and its
// host is in allowedHosts. On Windows it invokes rundll32's
// FileProtocolHandler directly rather than shelling through cmd /c start,
// which would re-parse the URL as command line input and allow argument
// injection.
func openBrowserValidated(rawURL string, allowedHosts []string) error {
	if err := validateOpenURL(rawURL, allowedHosts); err != nil {
		return err
	}
	return browserOpener(rawURL)
}

// validateOpenURL returns an error unless rawURL parses cleanly, uses https or
// loopback-only http, and has a host matching one of allowedHosts
// (case-insensitive, exact). An empty allowedHosts list skips the host check.
func validateOpenURL(rawURL string, allowedHosts []string) error {
	// Parse the URL and reject empty, hostless, or non-https targets.
	if rawURL == "" {
		return errors.New("empty browser url")
	}
	u, err := url.Parse(rawURL)
	if err != nil {
		return errors.Wrap(err, "parse browser url")
	}
	if u.Host == "" {
		return errors.New("browser url has no host")
	}
	if u.Scheme != "https" {
		if u.Scheme != "http" || !isLoopbackOpenHost(u.Hostname()) {
			return errors.Errorf(
				"browser url scheme must be https (or http for localhost), got %q",
				u.Scheme,
			)
		}
	}

	// Reject hosts outside the allowlist when one is configured.
	if len(allowedHosts) == 0 {
		return nil
	}
	host := strings.ToLower(u.Host)
	for _, allowed := range allowedHosts {
		if strings.ToLower(allowed) == host {
			return nil
		}
	}
	return errors.Errorf("browser url host %q is not in the allowlist", u.Host)
}

// isLoopbackOpenHost reports whether the browser-open target is a loopback host
// that is acceptable for local development.
func isLoopbackOpenHost(host string) bool {
	host = strings.ToLower(host)
	return host == "localhost" || host == "127.0.0.1" || host == "::1"
}

// hostsFromURLs parses each URL and returns the list of hosts. Empty or
// unparseable entries are skipped.
func hostsFromURLs(urls ...string) []string {
	hosts := make([]string, 0, len(urls))
	for _, raw := range urls {
		if raw == "" {
			continue
		}
		u, err := url.Parse(raw)
		if err != nil || u.Host == "" {
			continue
		}
		hosts = append(hosts, u.Host)
	}
	return hosts
}

// browserOpener opens the default browser to the given URL without shell
// interpretation. The URL must already be validated by validateOpenURL.
var browserOpener = openBrowser

func buildCreateSessionURL(apiEndpoint string) string {
	return strings.TrimRight(apiEndpoint, "/") + "/api/auth/session/create"
}

func buildHandoffBrowserURL(
	publicBaseURL string,
	payload string,
	authIntent string,
	username string,
) string {
	// Build the hash-route URL and append optional intent and username params.
	base := strings.TrimRight(publicBaseURL, "/") + "/#/auth/link/" + payload
	q := url.Values{}
	if authIntent != "" {
		q.Set("intent", authIntent)
	}
	if username != "" {
		q.Set("username", username)
	}
	qs := q.Encode()
	if qs == "" {
		return base
	}
	return base + "?" + qs
}

// buildHandoffWSURL returns the auth-session WebSocket URL for the endpoint.
func buildHandoffWSURL(apiEndpoint string, wsTicket string) string {
	wsURL := strings.Replace(apiEndpoint, "https://", "wss://", 1)
	wsURL = strings.Replace(wsURL, "http://", "ws://", 1)
	return strings.TrimRight(wsURL, "/") + "/api/auth/session/ws?tk=" + wsTicket
}
