// update rewrites the fixture's compiled module and output.
var update = flag.Bool("update", false, "rewrite the run-through fixture's module and output")

// harnessTSPath is the TypeScript copy of Harness the browser runner imports.
const harnessTSPath = "harness.gen.ts"

// harnessTS returns the content of harnessTSPath.
func harnessTS() ([]byte, error) {
	// Quote the harness as a JSON string, which is a valid TS literal.
	var a fastjson.Arena
	text := a.NewString(Harness).MarshalTo(nil)

	// Lead with the generated header and the declaration comment.
	var b bytes.Buffer
	b.WriteString("// Code generated by go test -update in sdk/function/run. DO NOT EDIT.\n\n")
	b.WriteString("// harness is the text of harness.js, which the Go runner embeds.\n")

	// Declare the constant as the quoted harness.
	b.WriteString("export const harness =\n  ")
	b.Write(text)
	b.WriteString("\n")
	return b.Bytes(), nil
}

// TestHarnessTS checks that the browser runner's copy of the harness matches
// harness.js.
func TestHarnessTS(t *testing.T) {
	// Generate the expected copy from harness.js.
	want, err := harnessTS()
	if err != nil {
		t.Fatal(err)
	}

	// Rewrite the copy when updating.
	if *update {
		if err := os.WriteFile(harnessTSPath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}

	// Otherwise the checked-in copy must match.
	got, err := os.ReadFile(harnessTSPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale, run go test -update", harnessTSPath)
	}
}

// fixturePath is the run-through fixture, which the browser runner test reads
// too.
const fixturePath = "testdata/down-instances.json"

// fixture is a PureFunction with an input and the output every runner must
// return.
type fixture struct {
	InputType  string
	OutputType string
	Source     string
	Module     string
	// Input is the input in protobuf JSON form.
	Input []byte
	// Output is the output in protobuf JSON form.
	Output []byte
}

// marshal encodes the fixture with one top-level field on each line.
func (fx *fixture) marshal() []byte {
	// Quote each string field.
	var a fastjson.Arena
	fields := []struct {
		name  string
		value []byte
	}{
		{"inputType", a.NewString(fx.InputType).MarshalTo(nil)},
		{"outputType", a.NewString(fx.OutputType).MarshalTo(nil)},
		{"source", a.NewString(fx.Source).MarshalTo(nil)},
		{"module", a.NewString(fx.Module).MarshalTo(nil)},
		{"input", fx.Input},
		{"output", fx.Output},
	}

	// Write each field on its own line.
	var b bytes.Buffer
	b.WriteString("{\n")
	for i, field := range fields {
		b.WriteString("  ")
		b.Write(a.NewString(field.name).MarshalTo(nil))
		b.WriteString(": ")
		b.Write(field.value)
		if i < len(fields)-1 {
			b.WriteByte(',')
		}
		b.WriteByte('\n')
	}
	b.WriteString("}\n")
	return b.Bytes()
}

// readFixture reads the run-through fixture.
func readFixture(t *testing.T) *fixture {
	// Read the fixture file.
	t.Helper()
	data, err := os.ReadFile(fixturePath)
	if err != nil {
		t.Fatal(err)
	}

	// Copy out each field.
	var p fastjson.Parser
	v, err := p.ParseBytes(data)
	if err != nil {
		t.Fatal(err)
	}
	return &fixture{
		InputType:  string(v.GetStringBytes("inputType")),
		OutputType: string(v.GetStringBytes("outputType")),
		Source:     string(v.GetStringBytes("source")),
		Module:     string(v.GetStringBytes("module")),
		Input:      v.Get("input").MarshalTo(nil),
		Output:     v.Get("output").MarshalTo(nil),
	}
}

// newTestRunner returns a runner that caches modules in a temporary directory.
func newTestRunner(t *testing.T) (*Runner, *bldr_util_qjsbytecode.Cache) {
	t.Helper()
	cache := bldr_util_qjsbytecode.NewCache(t.TempDir())
	le := logrus.NewEntry(logrus.New())
	return NewRunner(le, nil, cache), cache
}

// compileFunction compiles source into a PureFunction with a budget.
func compileFunction(t *testing.T, source string, budget *s4wave_function.Budget) *s4wave_function.PureFunction {
	t.Helper()
	module, err := s4wave_function.Compile(source)
	if err != nil {
		t.Fatal(err)
	}
	return &s4wave_function.PureFunction{
		Source:     source,
		Module:     module,
		InputType:  "s4wave.prom.QueryResponse",
		OutputType: "s4wave.prom.LabelSet",
		Budget:     budget,
	}
}

// TestRunThrough compiles the fixture's function, runs it on protobuf input
// to protobuf output, and reruns it from the cached bytecode.
func TestRunThrough(t *testing.T) {
	// Read the fixture and start a runner with an empty bytecode cache.
	ctx := context.Background()
	fx := readFixture(t)
	runner, cache := newTestRunner(t)

	// The fixture holds the module Compile gives its source.
	module, err := s4wave_function.Compile(fx.Source)
	if err != nil {
		t.Fatal(err)
	}
	if !*update && module != fx.Module {
		t.Fatalf("the fixture module is stale, run with -update:\n%s", module)
	}
	fn := &s4wave_function.PureFunction{
		Source:     fx.Source,
		Module:     module,
		InputType:  fx.InputType,
		OutputType: fx.OutputType,
	}

	// Run the function on the typed input.
	in := &s4wave_prom.QueryResponse{}
	if err := in.UnmarshalJSON(fx.Input); err != nil {
		t.Fatal(err)
	}
	out := &s4wave_prom.LabelSet{}
	if err := runner.Run(ctx, fn, in, out); err != nil {
		t.Fatal(err)
	}
	got, err := out.MarshalJSON()
	if err != nil {
		t.Fatal(err)
	}

	// Rewrite the fixture, or check the output against it.
	if *update {
		fx.Module = module
		fx.Output = got
		if err := os.WriteFile(fixturePath, fx.marshal(), 0o644); err != nil {
			t.Fatal(err)
		}
	} else {
		want := &s4wave_prom.LabelSet{}
		if err := want.UnmarshalJSON(fx.Output); err != nil {
			t.Fatal(err)
		}
		if !out.EqualVT(want) {
			t.Fatalf("output %s, want %s", got, fx.Output)
		}
	}
	t.Logf("output: %s", got)

	// The first run cached the module under the reactor build, name and
	// source.
	cacheFile := bldr_util_qjsbytecode.FileName(s4wave_function.ModuleName, []byte(module))
	cachePath := filepath.Join(cache.OwnerDir(bytecodeOwner), cacheFile)
	if _, err := os.Stat(cachePath); err != nil {
		t.Fatal(err)
	}

	// Replace the cached bytecode with another module's under the same name.
	// The next run links the cache entry instead of compiling the source.
	marker := compileBytecode(t, "export default () => ({ labels: [{ name: 'from', value: 'cache' }] })")
	if err := os.WriteFile(cachePath, marker, 0o644); err != nil {
		t.Fatal(err)
	}
	cached, err := runner.RunJSON(ctx, fn, fx.Input)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(cached, []byte(`"cache"`)) {
		t.Fatalf("the second run compiled the source: %s", cached)
	}

	// A different source has its own entry.
	other := compileFunction(t, "export default () => ({ labels: [{ name: 'from', value: 'source' }] })", nil)
	compiled, err := runner.RunJSON(ctx, other, fx.Input)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(compiled, []byte(`"source"`)) {
		t.Fatalf("a new source ran another module: %s", compiled)
	}
}

// compileBytecode compiles a module named ModuleName to bytecode in a
// separate instance.
func compileBytecode(t *testing.T, source string) []byte {
	// Compile the TS source to a module.
	t.Helper()
	ctx := context.Background()
	module, err := s4wave_function.Compile(source)
	if err != nil {
		t.Fatal(err)
	}

	// Start a separate QuickJS instance.
	rt := wazero.NewRuntime(ctx)
	defer rt.Close(ctx)
	qjs, err := quickjs.NewQuickJS(ctx, rt, wazero.NewModuleConfig())
	if err != nil {
		t.Fatal(err)
	}
	defer qjs.Close(ctx)
	if err := qjs.Init(ctx, []string{"qjs"}); err != nil {
		t.Fatal(err)
	}

	// Compile the module to bytecode under the function's module name.
	bytecode, err := qjs.CompileModule(ctx, module, s4wave_function.ModuleName)
	if err != nil {
		t.Fatal(err)
	}
	return bytecode
}

// TestRunBudget fails runs past their instruction or memory budget, and keeps
// a run within budget.
func TestRunBudget(t *testing.T) {
	// Start a runner and use an empty input.
	ctx := context.Background()
	runner, _ := newTestRunner(t)
	input := []byte(`{}`)

	// A loop that never ends passes its instruction budget, even inside try.
	loop := compileFunction(t, "export default () => { try { for (;;) {} } catch {} return {} }", &s4wave_function.Budget{InterruptChecks: 10})
	if _, err := runner.RunJSON(ctx, loop, input); !errors.Is(err, ErrInstructionBudget) {
		t.Fatalf("endless loop returned %v", err)
	}

	// A function that holds about 8 MiB passes a 4 MiB heap limit, well
	// inside the linear memory the runtime allows, and fits a 64 MiB limit.
	const hold = "export default () => { const a: number[][] = []; for (let i = 0; i < 128; i++) a.push(new Array(4096).fill(i)); return { labels: [{ name: 'n', value: String(a.length) }] } }"
	small := compileFunction(t, hold, &s4wave_function.Budget{MemoryLimitBytes: 4 << 20})
	if _, err := runner.RunJSON(ctx, small, input); !errors.Is(err, ErrMemoryBudget) {
		t.Fatalf("8 MiB under a 4 MiB limit returned %v", err)
	}
	large := compileFunction(t, hold, &s4wave_function.Budget{MemoryLimitBytes: 64 << 20})
	if _, err := runner.RunJSON(ctx, large, input); err != nil {
		t.Fatalf("8 MiB under a 64 MiB limit returned %v", err)
	}

	// The same loop with an end finishes within the default budget.
	bounded := compileFunction(t, "export default () => { let n = 0; for (let i = 0; i < 1e6; i++) n += i; return { labels: [{ name: 'n', value: String(n) }] } }", nil)
	out, err := runner.RunJSON(ctx, bounded, input)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(out, []byte(`"499999500000"`)) {
		t.Fatalf("bounded loop returned %s", out)
	}
}

// TestRunErrors reports a thrown error, a missing default export and a
// rejected import.
func TestRunErrors(t *testing.T) {
	// Start a runner and use an empty input.
	ctx := context.Background()
	runner, _ := newTestRunner(t)
	input := []byte(`{}`)

	// A thrown error is a FunctionError with its message.
	throws := compileFunction(t, "export default () => { throw new RangeError('no samples') }", nil)
	_, err := runner.RunJSON(ctx, throws, input)
	var fnErr *FunctionError
	if !errors.As(err, &fnErr) || fnErr.Message != "RangeError: no samples" {
		t.Fatalf("throwing function returned %v", err)
	}

	// A module without a default export function fails.
	noExport := compileFunction(t, "export const value = 1", nil)
	if _, err := runner.RunJSON(ctx, noExport, input); !errors.As(err, &fnErr) {
		t.Fatalf("module without a default export returned %v", err)
	}

	// A PureFunction cannot import.
	if _, err := s4wave_function.Compile("import { x } from './x'\nexport default () => x"); err == nil {
		t.Fatal("compile accepted an import")
	}
}
